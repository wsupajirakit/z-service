/** The gloss of a column heading in the given language ('' when the term is unknown). */
export function termGloss(raw: string, lang: Lang): string {
  const k = String(raw).replace(/\*\*/g, '').trim();
  const table = GLOSS[lang];
  return table[k] ?? table[k.toLowerCase()] ?? '';
}
